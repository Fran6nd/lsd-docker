/* the sea; the island solid from 42 beyond the window, on its side */
static void scene(bc_map *m, const stuck_case *c)
{
	int x, y, west = c->team == 1;

	for (y = 0; y < BC_MAP_Y; y++)
		for (x = 0; x < BC_MAP_X; x++) {
			uint64_t col = (uint64_t)1 << BC_MAP_WATER_Z;

			if (y >= 200 && y < 312 && (west ? x >= c->w.x0 + 16 && x < 256 : x < c->w.x0 && x >= 256))
				col = ~(uint64_t)0 << 42;
			m->col[y * BC_MAP_X + x] = col;
		}
	for (y = 0; y < 16; y++)
		for (x = 0; x < 16; x++)
			m->col[(c->w.y0 + y) * BC_MAP_X + c->w.x0 + x] = c->w.cols[y * 16 + x];
	m->rev++;
}

static int run_case(const stuck_case *c)
{
	static const char *const files[] = { "trees/default.bt", "trees/tdm.bt", "trees/ctf.bt", "trees/babel.bt" };
	bs_sim *s = bs_new(40, 4);
	char *all = calloc(1, 1 << 20), err[256];
	float far = 0.0f, best_feet = 99.0f;
	size_t q;
	int i, fz, out = 0;

	scene(s->truth, c);
	s->have_tents = 1;
	s->tent[0].x = 118.5f; s->tent[0].y = 256.5f; s->tent[0].z = 39.75f;
	s->tent[1].x = 394.5f; s->tent[1].y = 256.5f; s->tent[1].z = 40.75f;
	bs_start(s);
	for (q = 0; q < sizeof files / sizeof files[0]; q++) {
		char *t = bs_slurp(files[q]);

		if (t) { strcat(all, t); strcat(all, "\n"); free(t); }
	}
	if (!bc_engine_trees(s->e, all, err, sizeof err)) printf("  trees: %s\n", err);
	free(all);
	bs_set(s, BL_NO_PLAYER, "edit=all");
	bs_set(s, BL_NO_PLAYER, "tree=babel");
	bs_add(s, 0, 1, c->team, 10, BL_GUN_RIFLE, 4242u, c->x, c->y, c->team == 1 ? 1.0f : -1.0f, 0.0f);
	/* where it stood: the floor under the eye it had (crouched if it is
	 * only two high there, as it was) */
	fz = bc_map_floor_at_or_below(s->truth, (int)c->x, (int)c->y, (int)(c->z + 2.0f));
	bc_body_place(&s->p[0].body, s->truth, c->x, c->y, fz,
	              bc_map_solid(s->truth, (int)c->x, (int)c->y, fz - 3));
	for (i = 0; i < 60 * 90 && !out; i++) {
		float dx, dy, feet;

		s->p[0].blocks = 50;
		bs_step(s);
		if (!s->p[0].alive) break;
		dx = s->p[0].body.pos.x - c->x; dy = s->p[0].body.pos.y - c->y;
		feet = bc_body_feet(&s->p[0].body);
		if (sqrtf(dx * dx + dy * dy) > far) far = sqrtf(dx * dx + dy * dy);
		if (feet < best_feet) best_feet = feet;
		out = feet <= 43.0f || far >= 10.0f;
		if (i % (60 * 15) == 0 && getenv("BC_STUCK_SHOW")) {
			const bc_bot *b = bc_engine_bot(s->e, 0);
			char d[300];
			int k;

			d[0] = 0;
			bc_engine_describe(s->e, 0, d, sizeof d);
			printf("    t=%3ds at %.1f %.1f %.1f: %s\n", i / 60, s->p[0].body.pos.x, s->p[0].body.pos.y,
			       s->p[0].body.pos.z, d);
			if (b && b->mv.has_route) {
				printf("      route from %d,%d,%d:", b->mv.route.start.x, b->mv.route.start.y, b->mv.route.start.z);
				for (k = 0; k < b->mv.route.n && k < 4; k++)
					printf(" %s->%d,%d,%d%s%s", bc_nav_kind_name(b->mv.route.steps[k].kind), b->mv.route.steps[k].to.x,
					       b->mv.route.steps[k].to.y, b->mv.route.steps[k].to.z, b->mv.route.steps[k].digs ? " dig" : "",
					       b->mv.route.steps[k].builds ? " build" : "");
				printf("\n");
			}
		}
	}
	printf("  %-13s %s\n                floor %d: %s after %.0f s; farthest %.1f, highest feet %.1f, alive %d, edits %d\n",
	       c->name, c->seen, fz, out ? "OUT" : "STILL THERE", i / 60.0, far, best_feet, s->p[0].alive, s->edits);
	bs_free(s);
	return out;
}

int main(int argc, char **argv)
{
	size_t k;

	printf("babel: bots stuck in the cliff at sea level, each replayed alone\n");
	for (k = 0; k < sizeof CASES / sizeof CASES[0]; k++) {
		if (argc > 1 && strcmp(argv[1], CASES[k].name)) continue;
		CHECK(run_case(&CASES[k]));
	}
	printf("%d checks, %d failed\n", checks, failed);
	return failed != 0;
}
